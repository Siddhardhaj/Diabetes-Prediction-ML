import streamlit as st
import pandas as pd
import joblib

st.set_page_config(
    page_title="Diabetes Prediction",
    page_icon="🩺"
)

st.title("🩺 Diabetes Prediction")

st.write("Enter the patient information below.")

st.warning(
    "This application is for educational purposes only "
    "and is not a medical diagnosis."
)

st.subheader("Patient Information")

pregnancies = st.number_input(
    "Pregnancies",
    min_value=0,
    max_value=20,
    value=1,
    step=1
)

glucose = st.number_input(
    "Glucose",
    min_value=0.0,
    max_value=300.0,
    value=120.0,
    step=1.0
)

blood_pressure = st.number_input(
    "Blood Pressure",
    min_value=0.0,
    max_value=200.0,
    value=70.0,
    step=1.0
)

skin_thickness = st.number_input(
    "Skin Thickness",
    min_value=0.0,
    max_value=100.0,
    value=20.0,
    step=1.0
)

bmi = st.number_input(
    "BMI",
    min_value=0.0,
    max_value=80.0,
    value=25.0,
    step=0.1
)

diabetes_pedigree = st.number_input(
    "Diabetes Pedigree Function",
    min_value=0.0,
    max_value=3.0,
    value=0.47,
    step=0.01
)

age = st.number_input(
    "Age",
    min_value=1,
    max_value=120,
    value=30,
    step=1
)


if st.button("🔍 Predict Diabetes"):

    try:

        model = joblib.load("diabetes_model.pkl")

        input_data = pd.DataFrame({
            "Pregnancies": [pregnancies],
            "Glucose": [glucose],
            "BloodPressure": [blood_pressure],
            "SkinThickness": [skin_thickness],
            "BMI": [bmi],
            "DiabetesPedigreeFunction": [diabetes_pedigree],
            "Age": [age]
        })

        # Same zero-handling approach used during training
        original_data = pd.read_csv("diabetes.csv")

        zero_columns = [
            "Glucose",
            "BloodPressure",
            "SkinThickness",
            "BMI"
        ]

        for column in zero_columns:

            median_value = original_data[column].median()

            if input_data.loc[0, column] == 0:
                input_data.loc[0, column] = median_value

        # Make prediction
        prediction = model.predict(input_data)[0]

        st.subheader("Prediction Result")

        if prediction == 1:
            st.error("🔴 Diabetes Detected")
        else:
            st.success("🟢 No Diabetes Detected")

        # Probability
        if hasattr(model, "predict_proba"):

            probability = model.predict_proba(input_data)[0][1]

            st.write(
                f"Estimated probability of diabetes: "
                f"**{probability * 100:.2f}%**"
            )

        st.info(
            "This result is generated by a machine-learning model "
            "for educational purposes and should not be considered "
            "a medical diagnosis."
        )

    except Exception as e:

        st.error(f"Prediction error: {e}")
        
